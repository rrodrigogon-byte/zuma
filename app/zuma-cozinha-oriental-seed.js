/**
 * Provisiona a nova empresa Zuma Cozinha Oriental no banco de dados e memória do Kytto
 */
export async function provisionarZumaRestaurante({ commerceDb } = {}) {
  const resultados = {
    empresaProvisionada: false,
    lojaProvisionada: false,
    categoriasCriadas: 0,
    produtosCriados: 0,
    mesasCriadas: 0,
    clientesCriados: 0,
    storefrontProvisionado: false,
    canalWhatsappProvisionado: false,
    usuariosProvisionados: 0
  };

  try {
    const rootDb = db();
    rootDb.empresas ||= [];
    rootDb.lojas ||= [];
    rootDb.bar_mesas ||= [];
    rootDb.bar_produtos ||= [];
    rootDb.clientes ||= [];
    rootDb.usuarios ||= [];

    // 1. Empresa no Datastore JSON
    let empIdx = rootDb.empresas.findIndex(e => e.id === ZUMA_EMPRESA_ID || e.cnpj === ZUMA_CNPJ_NUM);
    const dadosEmp = {
      ...ZUMA_DADOS_EMPRESA,
      criadoEm: new Date().toISOString(),
      atualizadoEm: new Date().toISOString()
    };
    if (empIdx >= 0) {
      rootDb.empresas[empIdx] = { ...rootDb.empresas[empIdx], ...dadosEmp };
    } else {
      rootDb.empresas.push(dadosEmp);
    }
    resultados.empresaProvisionada = true;

    // 2. Loja no Datastore JSON
    let ljIdx = rootDb.lojas.findIndex(l => l.id === ZUMA_LOJA_ID);
    const dadosLj = {
      id: ZUMA_LOJA_ID,
      empresaId: ZUMA_EMPRESA_ID,
      codigo: "ZUMA-MATRIZ",
      nome: "Zuma Cozinha Oriental - Principal",
      nomeFantasia: "Zuma Cozinha Oriental",
      cnpj: ZUMA_CNPJ_NUM,
      telefone: "(65) 99800-1447",
      email: "contato@zumacozinhaoriental.com.br",
      enderecoLogradouro: "Av. Brasil",
      enderecoNumero: "1605",
      enderecoBairro: "Jardim Cidade Alta",
      enderecoCidade: "Tangará da Serra",
      enderecoEstado: "MT",
      enderecoCep: "78300000",
      timezone: "America/Cuiaba",
      ativa: true
    };
    if (ljIdx >= 0) {
      rootDb.lojas[ljIdx] = { ...rootDb.lojas[ljIdx], ...dadosLj };
    } else {
      rootDb.lojas.push(dadosLj);
    }
    resultados.lojaProvisionada = true;

    // 3. Mesas no Datastore JSON
    for (const m of ZUMA_MESAS_INICIAIS) {
      let mIdx = rootDb.bar_mesas.findIndex(x => x.empresa_id === ZUMA_EMPRESA_ID && x.numero === m.numero);
      const dadosMesa = {
        id: `mesa-zuma-${m.numero}`,
        empresa_id: ZUMA_EMPRESA_ID,
        numero: m.numero,
        nome: m.nome,
        tipo: m.tipo,
        capacidade: m.capacidade,
        setor: m.setor,
        ativa: true
      };
      if (mIdx >= 0) {
        rootDb.bar_mesas[mIdx] = { ...rootDb.bar_mesas[mIdx], ...dadosMesa };
      } else {
        rootDb.bar_mesas.push(dadosMesa);
      }
      resultados.mesasCriadas++;
    }

    // 4. Produtos no Datastore JSON
    for (const p of ZUMA_CARDAPIO_COMPLETO) {
      let pIdx = rootDb.bar_produtos.findIndex(x => x.empresa_id === ZUMA_EMPRESA_ID && x.nome === p.nome);
      const dadosProd = {
        id: `prod-zuma-${p.id}`,
        empresa_id: ZUMA_EMPRESA_ID,
        nome: p.nome,
        categoria: p.categoria,
        setor: p.setor,
        preco: p.preco,
        unidade: p.unidade,
        fator_estoque: 1,
        estoque_atual: p.estoque,
        estoque_minimo: p.minimo,
        ordem: p.ordem,
        descricao: p.descricao,
        foto: p.foto,
        cod_pdv: p.cod_pdv,
        ativo: true
      };
      if (pIdx >= 0) {
        rootDb.bar_produtos[pIdx] = { ...rootDb.bar_produtos[pIdx], ...dadosProd };
      } else {
        rootDb.bar_produtos.push(dadosProd);
      }
      resultados.produtosCriados++;
    }

    // 5. Clientes CRM no Datastore JSON
    for (const c of ZUMA_CLIENTES_CRM) {
      let cIdx = rootDb.clientes.findIndex(x => x.empresa_id === ZUMA_EMPRESA_ID && x.telefone === c.whatsapp);
      if (cIdx >= 0) {
        rootDb.clientes[cIdx] = { ...rootDb.clientes[cIdx], ...c, empresa_id: ZUMA_EMPRESA_ID, ativo: true };
      } else {
        rootDb.clientes.push({ ...c, empresa_id: ZUMA_EMPRESA_ID, ativo: true });
      }
      resultados.clientesCriados++;
    }

    save();
  } catch (jsonErr) {
    console.warn("[zuma-seed] Aviso no Datastore JSON:", jsonErr.message);
  }

  // 6. Sincronização no PostgreSQL se conectado
  if (commerceDb && typeof commerceDb.query === "function") {
    try {
      // 6.1 Empresa
      await commerceDb.query(`
        INSERT INTO empresas (
          id, nome, cnpj, razao_social, tipo_negocio, grupo_id,
          endereco_logradouro, endereco_numero, endereco_bairro, endereco_cidade, endereco_estado, endereco_cep,
          telefone, email, ativa, data_criacao, data_atualizacao
        ) VALUES (
          $1, $2, $3, $4, 'restaurante', $5,
          $6, $7, $8, $9, $10, $11,
          $12, $13, true, NOW(), NOW()
        ) ON CONFLICT (id) DO UPDATE SET
          nome = EXCLUDED.nome,
          razao_social = EXCLUDED.razao_social,
          cnpj = EXCLUDED.cnpj,
          tipo_negocio = 'restaurante',
          grupo_id = EXCLUDED.grupo_id,
          ativa = true,
          data_atualizacao = NOW();
      `, [
        ZUMA_EMPRESA_ID,
        ZUMA_DADOS_EMPRESA.nome,
        ZUMA_CNPJ_NUM,
        ZUMA_DADOS_EMPRESA.razaoSocial,
        ZUMA_GRUPO_ID,
        ZUMA_DADOS_EMPRESA.enderecoLogradouro,
        ZUMA_DADOS_EMPRESA.enderecoNumero,
        ZUMA_DADOS_EMPRESA.enderecoBairro,
        ZUMA_DADOS_EMPRESA.enderecoCidade,
        ZUMA_DADOS_EMPRESA.enderecoEstado,
        ZUMA_DADOS_EMPRESA.enderecoCep,
        ZUMA_DADOS_EMPRESA.telefone,
        ZUMA_DADOS_EMPRESA.email
      ]);

      // 6.2 Loja
      await commerceDb.query(`
        INSERT INTO lojas (
          id, empresa_id, codigo, nome, timezone, ativa, configuracoes, data_criacao, data_atualizacao
        ) VALUES (
          $1, $2, 'ZUMA-MATRIZ', $3, 'America/Cuiaba', true, '{}'::jsonb, NOW(), NOW()
        ) ON CONFLICT (id) DO UPDATE SET
          nome = EXCLUDED.nome,
          ativa = true,
          data_atualizacao = NOW();
      `, [
        ZUMA_LOJA_ID,
        ZUMA_EMPRESA_ID,
        "Zuma Cozinha Oriental - Principal"
      ]);

      // 6.3 Mesas
      for (const m of ZUMA_MESAS_INICIAIS) {
        try {
          await commerceDb.query(`
            INSERT INTO bar_mesas (
              empresa_id, numero, nome, tipo, ativa
            ) VALUES (
              $1, $2, $3, $4, true
            ) ON CONFLICT (empresa_id, numero) DO UPDATE SET
              nome = EXCLUDED.nome,
              tipo = EXCLUDED.tipo,
              ativa = true;
          `, [
            ZUMA_EMPRESA_ID,
            m.numero,
            m.nome,
            m.tipo
          ]);
        } catch (mErr) {}
      }

      // 6.4 Bar Produtos
      for (const p of ZUMA_CARDAPIO_COMPLETO) {
        try {
          await commerceDb.query(`
            INSERT INTO bar_produtos (
              empresa_id, nome, categoria, setor, preco, unidade, fator_estoque, estoque_atual, estoque_minimo, ordem, ativo
            ) VALUES (
              $1, $2, $3, $4, $5, $6, 1, $7, $8, $9, true
            ) ON CONFLICT (empresa_id, nome) DO UPDATE SET
              preco = EXCLUDED.preco,
              categoria = EXCLUDED.categoria,
              setor = EXCLUDED.setor,
              unidade = EXCLUDED.unidade,
              estoque_atual = EXCLUDED.estoque_atual,
              estoque_minimo = EXCLUDED.estoque_minimo,
              ordem = EXCLUDED.ordem,
              ativo = true;
          `, [
            ZUMA_EMPRESA_ID,
            p.nome,
            p.categoria,
            p.setor,
            p.preco,
            p.unidade,
            p.estoque,
            p.minimo,
            p.ordem
          ]);
        } catch (pErr) {}
      }

      // 6.5 Storefront & Aliases
      await commerceDb.query(`
        INSERT INTO commerce_storefronts (
          id, empresa_id, loja_id, codigo, nome, canal, status, moeda, timezone, configuracoes, criado_em, atualizado_em
        ) VALUES (
          $1, $2, $3, $4, $5, 'web', 'active', 'BRL', 'America/Cuiaba', '{}'::jsonb, NOW(), NOW()
        ) ON CONFLICT (id) DO UPDATE SET
          nome = EXCLUDED.nome,
          status = 'active',
          atualizado_em = NOW();
      `, [
        ZUMA_STOREFRONT_ID,
        ZUMA_EMPRESA_ID,
        ZUMA_LOJA_ID,
        ZUMA_COMMERCE_STOREFRONT.codigo,
        ZUMA_COMMERCE_STOREFRONT.nome
      ]);

      await commerceDb.query(`
        INSERT INTO commerce_store_domains (
          id, empresa_id, storefront_id, dominio, principal, criado_em
        ) VALUES (
          gen_random_uuid(), $1, $2, 'zuma.kytto.com.br', true, NOW()
        ) ON CONFLICT DO NOTHING;
      `, [
        ZUMA_EMPRESA_ID,
        ZUMA_STOREFRONT_ID
      ]);

      await commerceDb.query(`
        INSERT INTO commerce_storefront_aliases (
          id, empresa_id, storefront_id, alias, brand_key, ativo, public_config, criado_em, atualizado_em
        ) VALUES (
          gen_random_uuid(), $1, $2, 'zuma', 'zuma', true, $3::jsonb, NOW(), NOW()
        ) ON CONFLICT DO NOTHING;
      `, [
        ZUMA_EMPRESA_ID,
        ZUMA_STOREFRONT_ID,
        JSON.stringify(ZUMA_COMMERCE_STOREFRONT.publicConfig)
      ]);
      resultados.storefrontProvisionado = true;

      // 6.6 Canal WhatsApp Atendimento Ágil com Motor KyttoIA 2.5 Flash
      await commerceDb.query(`
        INSERT INTO canais_integracao (
          id, empresa_id, loja_id, provedor, nome, status, tipo_canal, configuracao, data_criacao, data_atualizacao
        ) VALUES (
          gen_random_uuid(), $1, $2, 'whatsapp', 'Atendimento Ágil Zuma', 'ativo', 'cliente', $3::jsonb, NOW(), NOW()
        ) ON CONFLICT DO NOTHING;
      `, [
        ZUMA_EMPRESA_ID,
        ZUMA_LOJA_ID,
        JSON.stringify(ZUMA_WHATSAPP_CONFIG)
      ]);
      resultados.canalWhatsappProvisionado = true;

    } catch (pgErr) {
      console.warn("[zuma-seed] Aviso ao provisionar no PostgreSQL:", pgErr.message);
    }
  }

  return resultados;
}
