CREATE TABLE IF NOT EXISTS tef_transacoes (
  id VARCHAR(80) PRIMARY KEY,
  empresa_id UUID NOT NULL REFERENCES empresas(id) ON DELETE CASCADE,
  loja_id UUID,
  terminal_id VARCHAR(80) REFERENCES tef_terminais(id) ON DELETE SET NULL,
  adquirente_id VARCHAR(40) NOT NULL,
  bandeira_id VARCHAR(40) NOT NULL,
  modalidade VARCHAR(30) NOT NULL,
  parcelas INT NOT NULL DEFAULT 1,
  valor_bruto NUMERIC(14,2) NOT NULL,
  taxa_mdr_pct NUMERIC(6,3) NOT NULL,
