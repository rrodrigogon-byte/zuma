  valor_liquido NUMERIC(14,2) NOT NULL,
  nsu VARCHAR(60) NOT NULL,
  codigo_autorizacao VARCHAR(60) NOT NULL,
  data_transacao TIMESTAMPTZ NOT NULL,
  data_previsao_liquidacao DATE NOT NULL,
  referencia_venda VARCHAR(80),
